-- Motorbikes, mopeds or trucks have no body, transmission or finition, and
-- may never have been registered: those properties become optional.
ALTER TABLE galette_auto_cars
  ALTER COLUMN car_first_registration_date DROP NOT NULL,
  ALTER COLUMN car_first_circulation_date DROP NOT NULL,
  ALTER COLUMN id_color DROP NOT NULL,
  ALTER COLUMN id_body DROP NOT NULL,
  ALTER COLUMN id_state DROP NOT NULL,
  ALTER COLUMN id_transmission DROP NOT NULL,
  ALTER COLUMN id_finition DROP NOT NULL;

ALTER TABLE galette_auto_history
  ALTER COLUMN id_color DROP NOT NULL,
  ALTER COLUMN id_state DROP NOT NULL;

-- Vehicle types: existing vehicles are cars
CREATE TABLE galette_auto_types (
  id_type integer GENERATED BY DEFAULT AS IDENTITY,
  type character varying(50) NOT NULL,
  PRIMARY KEY (id_type)
);

INSERT INTO galette_auto_types (type) VALUES ('Car');

ALTER TABLE galette_auto_cars ADD COLUMN id_type integer DEFAULT NULL;
UPDATE galette_auto_cars SET id_type = (SELECT MIN(id_type) FROM galette_auto_types);
ALTER TABLE galette_auto_cars
  ALTER COLUMN id_type SET NOT NULL,
  ADD CONSTRAINT galette_auto_cars_id_type_fkey FOREIGN KEY (id_type)
    REFERENCES galette_auto_types (id_type) ON DELETE RESTRICT ON UPDATE CASCADE;
CREATE INDEX galette_auto_cars_id_type_idx ON galette_auto_cars (id_type);
